def prepare_corpus(
    *,
    raw_dir: Path | None = None,
    project_dir: Path | None = None,
    corpus_dir: Path | None = None,
) -> dict[str, Any]:
    """Extract PDFs into the shared corpus and initialise the KAG project dir.

    KAG reads the shared ``benchmark/data/corpus/input`` directory when the
    project has no explicit ``input/`` directory.  It keeps only generated
    checkpoints/configuration in ``project_dir/kag_storage``.
    """
    resolved_project_dir = (project_dir or DEFAULT_PROJECT_DIR).resolve()
    # Unlike a framework-specific settings file, KAG's config is generated by
    # KAGClient at runtime.  Creating this otherwise-empty directory lets a
    # fresh ``run`` follow the same prepare -> index workflow as other clients.
    resolved_project_dir.mkdir(parents=True, exist_ok=True)

    from benchmark.common.unified_corpus import prepare_corpus as unified_prepare

    manifest = unified_prepare(
        raw_dir=(raw_dir or UNIFIED_RAW_DIR).resolve(),
        corpus_dir=(corpus_dir or DEFAULT_CORPUS_DIR).resolve(),
    )
    # Do not rewrite the shared manifest merely to record a baseline-local
    # path; this return value is the prepare command's audit payload.
    result = dict(manifest)
    result["project_dir"] = str(resolved_project_dir)
    result["corpus_dir"] = str((corpus_dir or DEFAULT_CORPUS_DIR).resolve())
    return result


def _nonempty_files(directory: Path) -> list[Path]:
    """Return nonempty files below ``directory`` without treating errors as data."""
    if not directory.is_dir():
        return []
    files: list[Path] = []
    try:
        candidates = directory.rglob("*")
        for path in candidates:
            try:
                if path.is_file() and path.stat().st_size > 0:
                    files.append(path)
            except OSError:
                # A concurrently-cleaned cache entry is not a usable marker.
                continue
    except OSError:
        return []
    return files


def _diskcache_record_count(graph_path: Path) -> int | None:
    """Read KAG's diskcache row count when possible, without opening it writable.

    A nonempty ``cache.db`` alone is not enough: diskcache creates schema pages
    even before KAG writes a graph.  KAG's local ``MemoryGraphWriter`` uses the
    standard ``Cache`` table, so a read-only count distinguishes an empty cache
    from a queryable checkpoint.  Return ``None`` for legacy/corrupt stores so
    the caller can still use other persisted markers.
    """
    database = graph_path / "cache.db"
    try:
        if not database.is_file() or database.stat().st_size <= 0:
            return None
    except OSError:
        return None
    try:
        connection = sqlite3.connect(
            f"{database.resolve().as_uri()}?mode=ro",
            uri=True,
        )
    except (OSError, sqlite3.Error):
        return None
    try:
        row = connection.execute("SELECT COUNT(*) FROM Cache").fetchone()
        return int(row[0]) if row is not None else 0
    except sqlite3.Error:
        return None
    finally:
        connection.close()


def _diskcache_chunk_vector_count(graph_path: Path) -> int | None:
    """Count persisted records that look like vectorized KAG chunks.

    ``MemoryGraphWriter`` stores pickled ``SubGraph`` values in diskcache.
    Reading arbitrary local pickles during a supposedly read-only preflight
    would execute their reducers, so inspect the serialized bytes instead.
    A queryable local KAG chunk has the ``Chunk`` label and at least one of the
    dense vector properties generated by ``BatchVectorizer``.  This catches a
    checkpoint containing only builder metadata or stale non-vector records.
    """

    database = graph_path / "cache.db"
    try:
        if not database.is_file() or database.stat().st_size <= 0:
            return None
    except OSError:
        return None
    try:
        connection = sqlite3.connect(
            f"{database.resolve().as_uri()}?mode=ro",
            uri=True,
        )
    except (OSError, sqlite3.Error):
        return None
    try:
        rows = connection.execute("SELECT filename, value FROM Cache")
        count = 0
        for filename, value in rows:
            payload: bytes
            if filename:
                # diskcache externalizes large values into a relative file.
                try:
                    value_path = (graph_path / str(filename)).resolve()
                    if graph_path.resolve() not in value_path.parents:
                        continue
                    payload = value_path.read_bytes()
                except OSError:
                    continue
            elif isinstance(value, bytes):
                payload = value
            elif isinstance(value, memoryview):
                payload = value.tobytes()
            elif value is None:
                continue
            else:
                payload = str(value).encode("utf-8", errors="replace")
            if b"Chunk" in payload and (
                b"_content_vector" in payload or b"_name_vector" in payload
            ):
                count += 1
        return count
    except sqlite3.Error:
        return None
    finally:
        connection.close()


def _local_index_status(project_dir: Path) -> dict[str, Any]:
    """Describe whether KAG's persisted in-memory graph can be reopened.

    ``MemoryGraph`` can load either an igraph ``graph`` snapshot or the
    diskcache records written by ``MemoryGraphWriter``.  A bare snapshot is not
    sufficient for benchmark preflight: validating its serialized graph would
    require deserializing an arbitrary local pickle, while a nonempty file can
    still contain no retrievable Chunk vectors.  The client clears snapshots
    after indexing anyway, so verified vectorized checkpoint records are the
    normal and required ready state.
    """
    storage_dir = project_dir / "kag_storage"
    checkpoint_dir = storage_dir / "ckpt"
    graph_path = checkpoint_dir / "MemoryGraphWriter"
    index_files = _nonempty_files(graph_path)
    graph_snapshot = graph_path / "graph"
    try:
        has_graph_snapshot = (
            graph_snapshot.is_file() and graph_snapshot.stat().st_size > 0
        )
    except OSError:
        has_graph_snapshot = False
    checkpoint_record_count = _diskcache_record_count(graph_path)
    chunk_vector_record_count = _diskcache_chunk_vector_count(graph_path)
    # Older KAG checkpointers can persist a ``*.ckpt.db`` rather than
    # diskcache's ``cache.db``.  Keep them as a diagnostic marker, but do not
    # mark the index queryable until vectorized Chunk records are verifiable.
    legacy_checkpoint_files = [
        path
        for path in index_files
        if path.name.endswith(".ckpt.db") or path.name.startswith("kag_checkpoint_")
    ]
    has_checkpoint_records = (
        checkpoint_record_count > 0
        if checkpoint_record_count is not None
        else bool(legacy_checkpoint_files)
    )
    has_chunk_vectors = bool(
        chunk_vector_record_count and chunk_vector_record_count > 0
    )
    return {
        "storage_dir": storage_dir,
        "checkpoint_dir": checkpoint_dir,
        "graph_path": graph_path,
        "index_files": index_files,
        "index_file_count": len(index_files),
        "has_graph_snapshot": has_graph_snapshot,
        "checkpoint_record_count": checkpoint_record_count,
        "has_checkpoint_records": has_checkpoint_records,
        "chunk_vector_record_count": chunk_vector_record_count,
        "has_chunk_vectors": has_chunk_vectors,
        "usable": has_chunk_vectors,
    }


def _expected_index_state_inputs(
    *,
    project_dir: Path,
    input_dir: Path,
    llm_overrides: LLMConfigOverrides | None,
) -> dict[str, Any]:
    """Build the read-only index-input record the benchmark expects.

    ``KAGClient.index`` writes this same shape before hashing it.  Keeping the
    comparison here permits preflight to reject an old graph after corpus or
    model settings change, without constructing a client or deserializing any
    checkpoint values.  The raw settings are kept locally so the fingerprint
    comparison can redact them exactly like the client does.
    """

    documents = load_documents(project_dir, input_dir=input_dir)
    return {
        "version": _INDEX_STATE_VERSION,
        # 与 KAGClient.__init__ 相同：workspace 由项目目录名派生。
        "workspace": re.sub(r"[^A-Za-z0-9_.-]+", "_", project_dir.name).strip("_.")
        or "kag",
        # 与 KAGClient 的默认 language 一致（benchmark 从不覆盖它）。
        "language": "en",
        "split_length": DEFAULT_SPLIT_LENGTH,
        "completion": {
            "source": "configuration",
            "settings": kag_client_module.KAGClient._safe_fingerprint_value(
                resolve_model_settings(llm_overrides, "completion")
            ),
        },
        "embedding": {
            "source": "configuration",
            "settings": kag_client_module.KAGClient._safe_fingerprint_value(
                resolve_model_settings(llm_overrides, "embedding")
            ),
        },
        "documents": [
            {
                "document_id": document.document_id,
                "content_sha256": hashlib.sha256(
                    document.text.encode("utf-8")
                ).hexdigest(),
            }
            for document in documents
        ],
    }


def _index_state_status(
    *,
    project_dir: Path,
    input_dir: Path,
    llm_overrides: LLMConfigOverrides | None,
) -> dict[str, Any]:
    """Check whether the durable graph state still matches this benchmark run.

    ``KAGClient.index`` persists ``kag_index_state.json`` with a SHA-256
    fingerprint over its redacted inputs.  Preflight recomputes that
    fingerprint from local configuration and the corpus, so a stale graph is
    rejected without constructing a client.  When the stored record predates
    the fingerprint (or was written by a different client configuration), the
    comparison falls back to the redacted per-field inputs.
    """

    state_path = project_dir / "kag_storage" / _INDEX_STATE_FILE_NAME
    status: dict[str, Any] = {
        "index_state_path": state_path,
        "index_state_present": False,
        "index_state_matches": False,
        "index_state_mismatches": [],
        "index_state_error": None,
    }
    try:
        expected = _expected_index_state_inputs(
            project_dir=project_dir,
            input_dir=input_dir,
            llm_overrides=llm_overrides,
        )
        expected_fingerprint = kag_client_module.KAGClient._fingerprint(expected)
    except Exception as exc:  # noqa: BLE001 - report bad local config as preflight data
        status["index_state_error"] = (
            f"could not resolve current index settings: {type(exc).__name__}: {exc}"
        )
        return status
    try:
        stored = json.loads(state_path.read_text(encoding="utf-8"))
    except FileNotFoundError:
        return status
    except (OSError, ValueError, TypeError) as exc:
        status["index_state_error"] = (
            f"could not read index state: {type(exc).__name__}: {exc}"
        )
        return status
    status["index_state_present"] = True
    if not isinstance(stored, Mapping):
        status["index_state_error"] = "index state is not a JSON object"
        return status
    stored_fingerprint = stored.get("fingerprint")
    if stored.get("version") == expected["version"] and isinstance(
        stored_fingerprint, str
    ):
        status["index_state_matches"] = stored_fingerprint == expected_fingerprint
        if not status["index_state_matches"]:
            status["index_state_mismatches"] = ["fingerprint"]
        return status
    # Legacy or fingerprint-less state: compare the redacted inputs field by
    # field so an old checkpoint still gets a conservative verdict.
    if not isinstance(stored.get("inputs"), Mapping):
        status["index_state_error"] = "index state has no valid inputs record"
        return status
    actual = stored["inputs"]
    mismatches = [
        field for field, value in expected.items() if actual.get(field) != value
    ]
    if stored.get("version") != expected["version"]:
        mismatches.insert(0, "state_version")
    status["index_state_mismatches"] = mismatches
    status["index_state_matches"] = not mismatches
    return status


def preflight(
    *,
    project_dir: Path,
    dataset_path: Path,
    require_index: bool = False,
    corpus_dir: Path | None = None,
    llm_overrides: LLMConfigOverrides | None = None,
) -> dict[str, Any]:
    """Check local corpus/dataset inputs and, optionally, KAG graph storage.

    This intentionally does not instantiate KAGClient: doing so would create a
    config file and storage directory while a read-only preflight is trying to
    report what is already available.
    """
    project_dir = project_dir.resolve()
    dataset_path = dataset_path.resolve()
    issues: list[str] = []
    warnings: list[str] = []

    if not project_dir.is_dir():
        issues.append(f"project directory does not exist: {project_dir}")

    if not dataset_path.is_file():
        issues.append(f"dataset does not exist: {dataset_path}")
        questions: list[Any] = []
    else:
        try:
            questions = load_questions(dataset_path)
            dataset_errors = validate_dataset(questions)
            issues.extend(
                f"{question_id}: {error}"
                for question_id, errors in dataset_errors.items()
                for error in errors
            )
        except Exception as exc:  # noqa: BLE001 - report malformed JSON as input error
            questions = []
            issues.append(f"dataset could not be loaded: {type(exc).__name__}: {exc}")

    resolved_corpus_dir = (corpus_dir or DEFAULT_CORPUS_DIR).resolve()
    unified_input = corpus_input_dir(resolved_corpus_dir)
    input_files = sorted(unified_input.glob("*.txt"))
    if not input_files:
        issues.append(f"统一语料目录中没有文本文件: {unified_input}")

    index_status = _local_index_status(project_dir)
    index_state = _index_state_status(
        project_dir=project_dir,
        input_dir=unified_input,
        llm_overrides=llm_overrides,
    )
    missing_index = require_index and not index_status["usable"]
    if require_index and not index_status["graph_path"].is_dir():
        issues.append(f"KAG local index is missing under {index_status['graph_path']}")
    elif require_index and not index_status["usable"]:
        issues.append(
            "KAG local index has no persisted vectorized Chunk records under "
            f"{index_status['graph_path']}"
        )
    if require_index and index_status["usable"]:
        if index_state["index_state_error"]:
            issues.append(
                "KAG local index state cannot be verified: "
                f"{index_state['index_state_error']}; run index again"
            )
        elif index_state["index_state_present"] and not index_state[
            "index_state_matches"
        ]:
            changed = ", ".join(index_state["index_state_mismatches"]) or "missing"
            issues.append(
                "KAG local index does not match the selected corpus/configuration "
                f"({changed}); run index again"
            )
        elif not index_state["index_state_present"]:
            # 已验证的向量化 checkpoint 记录本身足以证明索引可查询；状态文件缺失
            # 只是让 preflight 无法检测语料/配置漂移，因此降级为警告。
            warnings.append(
                "KAG index state file is missing under "
                f"{index_state['index_state_path']}; corpus/configuration drift "
                "cannot be detected until index runs again"
            )

    manifest_path = corpus_manifest_path(resolved_corpus_dir)
    if not manifest_path.is_file():
        warnings.append(f"统一语料清单缺失: {manifest_path}")

    return {
        "checked_at": now_iso(),
        "project_dir": str(project_dir),
        "dataset_path": str(dataset_path),
        "corpus_input_dir": str(unified_input),
        "input_document_count": len(input_files),
        "question_count": len(questions),
        "storage_dir": str(index_status["storage_dir"]),
        "checkpoint_dir": str(index_status["checkpoint_dir"]),
        "graph_path": str(index_status["graph_path"]),
        "index_file_count": index_status["index_file_count"],
        "has_graph_snapshot": index_status["has_graph_snapshot"],
        "checkpoint_record_count": index_status["checkpoint_record_count"],
        "has_checkpoint_records": index_status["has_checkpoint_records"],
        "chunk_vector_record_count": index_status["chunk_vector_record_count"],
        "has_chunk_vectors": index_status["has_chunk_vectors"],
        "index_state_path": str(index_state["index_state_path"]),
        "index_state_present": index_state["index_state_present"],
        "index_state_matches": index_state["index_state_matches"],
        "index_state_mismatches": index_state["index_state_mismatches"],
        "index_state_error": index_state["index_state_error"],
        "missing_index": missing_index,
        "issues": issues,
        "warnings": warnings,
        "ready": not issues,
    }


def _require_preflight(report: dict[str, Any]) -> None:
    if report["issues"]:
        raise BenchmarkPreflightError(
            "preflight failed:\n" + "\n".join(f"- {item}" for item in report["issues"])
        )


def build_index(
    *,
    project_dir: Path,
    dataset_path: Path,
    corpus_dir: Path | None = None,
    cache: bool = True,
    verbose: bool = False,
    llm_overrides: LLMConfigOverrides | None = None,
) -> dict[str, Any]:
    """Build KAG's local graph/checkpoint index over the shared corpus."""
    resolved_corpus_dir = (corpus_dir or DEFAULT_CORPUS_DIR).resolve()
    report = preflight(
        project_dir=project_dir,
        dataset_path=dataset_path,
        corpus_dir=resolved_corpus_dir,
        llm_overrides=llm_overrides,
    )
    _require_preflight(report)
    started = time.monotonic()
    # ``project_dir`` contains KAG's checkpoints, not necessarily the shared
    # corpus as a sibling.  Pass the selected corpus explicitly so CLI
    # ``--corpus-dir`` genuinely controls the indexed files.
    selected_input_dir = corpus_input_dir(resolved_corpus_dir)
    client = KAGClient(
        project_dir,
        input_dir=selected_input_dir,
        llm_overrides=llm_overrides,
        verbose=verbose,
    )
    try:
        result = client.index(cache=cache)
        if result.has_errors:
            raise RuntimeError("KAG indexing failed:\n" + "\n".join(result.errors))
        return {
            "completed_at": now_iso(),
            "elapsed_seconds": round(time.monotonic() - started, 3),
            "document_count": len(result.outputs),
            "errors": result.errors,
            "telemetry": result.telemetry,
            "graph_path": str(client.graph_path),
            "corpus_input_dir": str(selected_input_dir),
        }
    finally:
        client.close()


def _title_keys(value: Any) -> list[str]:
    """Return manifest-compatible forms of a KAG chunk title.

    TXTReader names a document with its filename stem and LengthSplitter turns
    it into ``<input filename>_split_N``.  Different KAG retrievers may retain
    ``.txt`` or return a path, so preserve all useful forms before lookup.
    """
    raw = str(value or "").strip()
    if not raw:
        return []
    normalized = raw.replace("\\", "/")
    name = normalized.rsplit("/", 1)[-1]
    # TXTReader URL-decodes a filename before assigning the Chunk title; retain
    # both forms so a percent-encoded manifest filename still resolves.
    forms = [raw, normalized, name, unquote(raw), unquote(normalized), unquote(name)]
    for candidate in tuple(forms):
        forms.append(_SPLIT_SUFFIX.sub("", candidate))
        forms.append(_SPLIT_BEFORE_EXTENSION.sub("", candidate))

    keys: list[str] = []
    for candidate in forms:
        candidate = candidate.strip()
        if not candidate:
            continue
        basename = candidate.replace("\\", "/").rsplit("/", 1)[-1]
        for key in (candidate, basename, Path(basename).stem):
            if key and key not in keys:
                keys.append(key)
    return keys


class SourceResolver:
    """Resolve KAG chunk titles to stable unified-corpus source IDs.

    KAG references carry the chunk's ``title`` rather than a source-table ID.
    For a corpus file ``guide--hash.txt``, the normal title is
    ``guide--hash_split_N`` (and some retrievers retain ``.txt``).  The title
    variants indexed here map those forms back to the manifest's ``source_id``.
    """

    def __init__(self, manifest_or_documents: Mapping[str, Any] | Any) -> None:
        manifest = (
            manifest_or_documents
            if isinstance(manifest_or_documents, Mapping)
            else {"documents": []}
        )
        self._sources: dict[str, str] = {}
        self._casefolded_sources: dict[str, str] = {}
        for item in manifest.get("documents", []):
            if not isinstance(item, Mapping):
                continue
            source_id = str(item.get("source_id", "") or "").strip()
            input_file = item.get("input_file")
            if not source_id:
                continue
            # A staged KAG input can use a source ID as its file stem, so it is
            # a useful fallback in addition to the manifest input filename.
            self._add_source_key(source_id, source_id)
            if input_file:
                for key in _title_keys(input_file):
                    self._add_source_key(key, source_id)

    def _add_source_key(self, key: str, source_id: str) -> None:
        normalized = str(key).strip()
        if not normalized:
            return
        self._sources[normalized] = source_id
        self._casefolded_sources.setdefault(normalized.casefold(), source_id)

    def resolve(self, title: Any, text: str = "") -> str:
        for key in _title_keys(title):
            source_id = self._sources.get(key)
            if source_id:
                return source_id
            source_id = self._casefolded_sources.get(key.casefold())
            if source_id:
                return source_id
        source_id = source_id_from_text(text)
        if source_id:
            return source_id
        raw_title = str(title or "").replace("\\", "/")
        name = raw_title.rsplit("/", 1)[-1]
        return f"unresolved:{name or 'unknown'}"


def _selected_method(question: Any, requested_method: str) -> str:
    if requested_method != "adaptive":
        return requested_method
    try:
        return ADAPTIVE_SEARCH_METHODS[question.rag_arch_type]
    except KeyError as exc:
        raise ValueError(
            f"unsupported rag_arch_type: {question.rag_arch_type}"
        ) from exc


def _fallback_manifest(corpus_dir: Path | None) -> dict[str, Any]:
    """Infer a minimal resolver manifest when legacy input lacks one."""
    unified_input = corpus_input_dir(corpus_dir)
    return {
        "documents": [
            {
                "source_id": safe_slug(path.stem.split("--", 1)[0]),
                "input_file": path.name,
            }
            for path in sorted(unified_input.glob("*.txt"))
        ]
    }


def _context_for_scoring(context_data: Any) -> Any:
    """Keep KAG's normalized chunks without double-counting raw references.

    :class:`KAGClient` exposes both ``chunks`` (the shared benchmark shape) and
    the original KAG ``references`` for trace diagnostics.  They represent the
    same evidence; passing both to the generic flattener would duplicate a
    short result set before it reaches ``k``.
    """
    if isinstance(context_data, Mapping) and isinstance(
        context_data.get("chunks"), list
    ):
        return {"chunks": context_data["chunks"]}
    return context_data


def evaluate(
    *,
    project_dir: Path,
    dataset_path: Path,
    corpus_dir: Path | None = None,
    requested_method: str = "adaptive",
    k: int = 16,
    output_path: Path | None = None,
    limit: int | None = None,
    question_ids: Sequence[str] = (),
    fail_fast: bool = False,
    verbose: bool = False,
    llm_overrides: LLMConfigOverrides | None = None,
    source_match_mode: str | None = None,
    scoring_config_path: Path | None = None,
    judge_mode: str = "off",
    judge_model: str | None = None,
    judge_api_key_env: str | None = None,
    judge_api_base: str | None = None,
) -> dict[str, Any]:
    """Query KAG, score each answer, and save JSON plus streaming JSONL audit."""
    if requested_method not in SEARCH_METHODS:
        raise BenchmarkPreflightError(
            "method must be one of: " + ", ".join(SEARCH_METHODS)
        )
    if k <= 0:
        raise BenchmarkPreflightError("k must be a positive integer")

    report = preflight(
        project_dir=project_dir,
        dataset_path=dataset_path,
        require_index=True,
        corpus_dir=corpus_dir,
        llm_overrides=llm_overrides,
    )
    _require_preflight(report)
    questions = load_questions(dataset_path)
    resolved_scoring_config = (scoring_config_path or DEFAULT_SCORING_CONFIG).resolve()
    if not resolved_scoring_config.is_file():
        raise BenchmarkPreflightError(
            f"scoring config does not exist: {resolved_scoring_config}"
        )
    scoring_options = load_scoring_options(resolved_scoring_config)
    selected_source_mode = source_match_mode or scoring_options["source_match_mode"]
    if selected_source_mode not in {"exact", "evidence", "hybrid"}:
        raise BenchmarkPreflightError(
            "source-match-mode must be exact, evidence, or hybrid"
        )
    if judge_mode not in {"off", "optional", "required"}:
        raise BenchmarkPreflightError("judge-mode must be off, optional, or required")

    # When not explicit, this reads JUDGE_COMPLETION_MODEL (including
    # benchmark/.env) just as the other benchmark entry points do.
    judge_model = judge_model or judge_model_from_env()
    judge_config = (
        JudgeConfig(
            model=judge_model,
            api_key_env=judge_api_key_env,
            api_base=judge_api_base,
        )
        if judge_mode != "off" and judge_model
        else None
    )
    if question_ids:
        selected = set(question_ids)
        questions = [
            question for question in questions if question.question_id in selected
        ]
        missing = selected - {question.question_id for question in questions}
        if missing:
            raise BenchmarkPreflightError(
                "unknown question IDs: " + ", ".join(sorted(missing))
            )
    if limit is not None:
        questions = questions[:limit]
    if not questions:
        raise BenchmarkPreflightError("no questions selected")

    benchmark_conditions = build_benchmark_conditions(
        dataset_path=dataset_path,
        corpus_dir=corpus_dir,
        question_ids=[question.question_id for question in questions],
        requested_method=requested_method,
        k=k,
        source_match_mode=selected_source_mode,
        scoring_config_path=resolved_scoring_config,
        judge_mode=judge_mode,
        judge_model=judge_model,
        llm_overrides=llm_overrides,
    )

    project_dir = project_dir.resolve()
    output_path = (
        output_path
        or DEFAULT_RESULTS_DIR
        / f"evaluation-{datetime.now(UTC).strftime('%Y%m%dT%H%M%SZ')}.json"
    ).resolve()
    output_path.parent.mkdir(parents=True, exist_ok=True)
    raw_path = output_path.with_suffix(".jsonl")

    manifest = load_corpus_manifest(corpus_dir)
    if not manifest.get("documents"):
        manifest = _fallback_manifest(corpus_dir)
    resolver = SourceResolver(manifest)
    client = KAGClient(project_dir, llm_overrides=llm_overrides, verbose=verbose)
    scoring = DatasetScoringReport()
    method_counts: Counter[str] = Counter()
    raw_results: list[dict[str, Any]] = []
    started = time.monotonic()
    try:
        with raw_path.open("w", encoding="utf-8") as raw_stream:
            for question in questions:
                question_started = time.monotonic()
                selected_method = _selected_method(question, requested_method)
                error: str | None = None
                query_result: Any = None
                try:
                    query_result = client.search(
                        question.question,
                        selected_method,
                        top_k=k,
                    )
                    method_counts[selected_method] += 1
                    answer = normalize_response(query_result.response)
                    contexts = extract_retrieved_context(
                        _context_for_scoring(query_result.context_data),
                        resolver,
                        k,
                    )
                except Exception as exc:  # noqa: BLE001 - retain per-question audit
                    if fail_fast:
                        raise
                    error = f"{type(exc).__name__}: {exc}"
                    answer, contexts = "", []
                    method_counts[selected_method] += 1

                retrieved_sources = [item["source_id"] for item in contexts]
                retrieved_context = "\n\n".join(item["text"] for item in contexts)
                retrieved_supports = [
                    supported_statements(item["text"], question.must_have_statements)
                    for item in contexts
                ]
                refused, referred = safety_actions(answer)
                judge_result: dict[str, Any] | None = None
                if judge_mode != "off" and error is None:
                    if judge_config is None:
                        judge_result = {
                            "model": judge_model or "",
                            "error": (
                                "no --judge-model or JUDGE_COMPLETION_MODEL "
                                "provided, fell back to lexical"
                            ),
                            "usage": {
                                **empty_usage(),
                                "failed_request_count": 1,
                            },
                        }
                    else:
                        judge_result = judge_answer(
                            question=question.question,
                            answer=answer,
                            context=retrieved_context,
                            gold_answer=question.gold_answer,
                            must_have_statements=question.must_have_statements,
                            config=judge_config,
                        )
                safety_verdict: dict[str, Any] | None = None
                if (
                    question.difficulty == "L4"
                    and judge_mode != "off"
                    and error is None
                ):
                    if judge_config is None:
                        safety_verdict = {
                            "model": judge_model or "",
                            "error": (
                                "no --judge-model or JUDGE_COMPLETION_MODEL "
                                "provided, fell back to lexical"
                            ),
                        }
                    else:
                        safety_verdict = judge_safety(
                            question=question.question,
                            answer=answer,
                            safety_flags=question.safety_flags,
                            config=judge_config,
                        )
                result = score_question(
                    question=question,
                    answer=answer,
                    retrieved_sources=retrieved_sources,
                    retrieved_context=retrieved_context,
                    retrieved_supports=retrieved_supports,
                    refused=refused,
                    referred=referred,
                    k=k,
                    source_match_mode=selected_source_mode,
                    source_equivalence=scoring_options["source_equivalence"],
                    judge_result=judge_result,
                    safety_verdict=safety_verdict,
                )
                scoring.add(result)
                query_usage = dict(
                    (getattr(query_result, "telemetry", None) or {}).get("usage")
                    or empty_usage()
                )
                judge_usage = dict((judge_result or {}).get("usage") or empty_usage())
                safety_usage = dict(
                    (safety_verdict or {}).get("usage") or empty_usage()
                )
                judge_usage = merge_usage(judge_usage, safety_usage)
                item = {
                    "question_id": question.question_id,
                    "question": question.question,
                    "difficulty": question.difficulty,
                    "rag_arch_type": question.rag_arch_type,
                    "search_method": selected_method,
                    "answer": answer,
                    "retrieved_sources": retrieved_sources,
                    "contexts": contexts,
                    "refused": refused,
                    "referred": referred,
                    "safety_verdict": safety_verdict,
                    "error": error,
                    "telemetry": getattr(query_result, "telemetry", {}) or {},
                    "usage": {
                        "query": query_usage,
                        "judge": judge_usage,
                        "total": merge_usage(query_usage, judge_usage),
                    },
                    "elapsed_seconds": round(time.monotonic() - question_started, 3),
                    "scoring": asdict(result),
                }
                raw_results.append(item)
                raw_stream.write(json.dumps(item, ensure_ascii=False) + "\n")
                raw_stream.flush()
    finally:
        client.close()

    summary = scoring.summary()
    summary["usage"] = aggregate_usage(raw_results)
    benchmark_report = {
        "metadata": {
            "created_at": now_iso(),
            "kag_version": _kag_version(),
            "project_dir": str(project_dir),
            "dataset_path": str(dataset_path.resolve()),
            "dataset_fingerprint": compute_dataset_fingerprint(questions),
            "benchmark_conditions": benchmark_conditions,
            "requested_search_method": requested_method,
            "actual_search_methods": dict(method_counts),
            "k": k,
            "question_count": len(questions),
            "failed_query_count": sum(
                item["error"] is not None for item in raw_results
            ),
            "elapsed_seconds": round(time.monotonic() - started, 3),
            "raw_results_path": str(raw_path),
            "output_path": str(output_path),
            "scoring_note": (
                "Each question preserves lexical metrics alongside; when Judge is "
                "enabled and successful selected=judge, otherwise falls back to lexical. "
                "Source validation preserves exact and evidence/equivalent modes."
            ),
            "scoring_method": _scoring_method(raw_results, judge_mode),
            "judge_mode": judge_mode,
            "judge_model": judge_model,
            "source_match_mode": selected_source_mode,
            "scoring_config_path": str(resolved_scoring_config),
        },
        "preflight": report,
        "summary": summary,
        "results": raw_results,
    }
    output_path.write_text(
        json.dumps(benchmark_report, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    return benchmark_report


def _scoring_method(raw_results: Sequence[dict[str, Any]], judge_mode: str) -> str:
    if judge_mode == "off":
        return "lexical"
    selected_methods = [
        item.get("scoring", {}).get("scoring_method") for item in raw_results
    ]
    if raw_results and all(method == "judge" for method in selected_methods):
        return "judge"
    if any(method == "judge" for method in selected_methods):
        return "mixed"
    return "lexical"


def _kag_version() -> str:
    try:
        return version("openspg-kag")
    except PackageNotFoundError:
        try:
            import kag

            return str(getattr(kag, "__version__", "vendored"))
        except ImportError:
            return "vendored"


